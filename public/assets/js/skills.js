  function normalize(text) {
    return String(text || '')
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .trim();
  }

  function countMatches(text, keywords) {
    const t = normalize(text);
    let n = 0;
    for (const kw of keywords) {
      if (t.includes(normalize(kw))) n++;
    }
    return n;
  }

  function detectSkill(text, mode) {
    const candidates = mode
      ? SKILLS.filter(s => (s.modes || []).includes(mode))
      : SKILLS;

    let best = null;
    let bestScore = 0;

    for (const s of candidates) {
      let score = countMatches(text, s.keywords || []);

      // Bonus por coincidencia con el nombre
      if (normalize(text).includes(normalize(s.name))) score += 3;
      if (normalize(text).includes(s.id)) score += 2;

      if (score > bestScore) {
        bestScore = score;
        best = s;
      }
    }

    if (!best || bestScore === 0) {
      return SKILLS.find(s => s.id === 'explain') || null;
    }
    return best;
  }

  function detectAll(text, mode) {
    const candidates = mode
      ? SKILLS.filter(s => (s.modes || []).includes(mode))
      : SKILLS;

    return candidates
      .map(s => ({ skill: s, score: countMatches(text, s.keywords || []) }))
      .filter(x => x.score > 0)
      .sort((a, b) => b.score - a.score)
      .map(x => x.skill);
  }

  function detectCombos(text) {
    return COMBOS.filter(c =>
      c.skills.some(id => {
        const s = SKILLS.find(x => x.id === id);
        return s && countMatches(text, s.keywords || []) > 0;
      })
    );
  }

